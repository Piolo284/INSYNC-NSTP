import React, { useState } from 'react';
import { Download, FileSpreadsheet, FileJson, ArrowLeft, FileText } from 'lucide-react';
import { useNavigate } from 'react-router-dom';
import TopBar from '../components/TopBar';
import { studentsApi } from '../api/students';
import { cadetsApi } from '../api/cadets';
import { gradesApi } from '../api/grades';
import { toCsv, downloadCsvString } from '../api/client';
import { errorMessage } from '../hooks/useApi';
import { useAuth } from '../context/AuthContext';

const COLUMNS = [
  { label: 'ID', value: 'id' },
  { label: 'Name', value: 'name' },
  { label: 'Program', value: 'program' },
  { label: 'Course', value: 'course' },
  { label: 'Year Level', value: 'yearLevel' },
  { label: 'Section', value: 'section' },
  { label: 'Email', value: 'email' },
  { label: 'Status', value: 'status' },
];

async function fetchTraineeRows(effectiveProgram) {
  const wantsStudents = effectiveProgram !== 'ROTC';
  const wantsCadets = effectiveProgram !== 'CWTS';

  const [studentRes, cadetRes] = await Promise.all([
    wantsStudents ? studentsApi.list() : Promise.resolve({ data: [] }),
    wantsCadets ? cadetsApi.list() : Promise.resolve({ data: [] }),
  ]);

  const students = (studentRes.data || []).map((s) => ({
    id: s.studentId, name: s.fullName, program: 'CWTS', course: s.course,
    yearLevel: s.yearLevel, section: s.section, email: s.email, status: s.status,
  }));
  const cadets = (cadetRes.data || []).map((c) => ({
    id: c.cadetId, name: c.fullName, program: 'ROTC', course: c.course,
    yearLevel: c.yearLevel, section: c.section, email: c.email, status: c.status,
  }));

  return [...students, ...cadets];
}

export default function ExportData() {
  const navigate = useNavigate();
  const { effectiveProgram } = useAuth();
  const [busy, setBusy] = useState('');
  const [error, setError] = useState('');

  const handleExport = async (type) => {
    setError('');
    setBusy(type);
    try {
      if (type === 'grades-csv') {
        await gradesApi.exportReport(
          effectiveProgram && effectiveProgram !== 'All' ? { program: effectiveProgram } : undefined,
          'grade-report.csv'
        );
        return;
      }

      const rows = await fetchTraineeRows(effectiveProgram);
      if (type === 'csv') {
        const csv = toCsv(rows, COLUMNS);
        downloadCsvString(csv, 'trainee-list.csv');
      } else if (type === 'json') {
        const blob = new Blob([JSON.stringify(rows, null, 2)], { type: 'application/json' });
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.href = url;
        link.download = 'trainee-list.json';
        document.body.appendChild(link);
        link.click();
        link.remove();
        URL.revokeObjectURL(url);
      }
    } catch (err) {
      setError(errorMessage(err, 'Export failed. Please try again.'));
    } finally {
      setBusy('');
    }
  };

  const exportOptions = [
    { id: 'csv', label: 'Export Trainee List as CSV', desc: 'Download student/cadet records in CSV format for Excel', icon: FileSpreadsheet, color: '#059669', bg: '#ECFDF5' },
    { id: 'json', label: 'Export Trainee List as JSON', desc: 'Export raw trainee data in JSON format for developers', icon: FileJson, color: '#2563EB', bg: '#EFF6FF' },
    { id: 'grades-csv', label: 'Export Grade Report as CSV', desc: 'Download the official final grade report generated by the server', icon: FileText, color: '#DC2626', bg: '#FEF2F2' },
  ];

  return (
    <div style={{ minHeight: '100vh', paddingBottom: '40px' }}>
      <TopBar title="Export Data" showBreadcrumb={true} />

      <main style={{ padding: '24px' }}>
        <button
          onClick={() => navigate('/students')}
          style={{ display: 'flex', alignItems: 'center', gap: '6px', marginBottom: '20px', background: 'none', border: 'none', color: 'var(--text-secondary)', fontSize: '14px', fontWeight: 500, cursor: 'pointer', fontFamily: 'inherit', padding: '6px 10px', borderRadius: '8px' }}
        >
          <ArrowLeft size={16} /> Back to Students
        </button>

        <div style={{ background: 'var(--card-bg)', borderRadius: 'var(--radius)', padding: '32px', boxShadow: 'var(--shadow)', border: '1px solid var(--border)', maxWidth: '700px' }}>
          <h2 style={{ fontSize: '22px', fontWeight: 800, margin: '0 0 8px', color: 'var(--text-primary)' }}>Export Data</h2>
          <p style={{ fontSize: '14px', color: 'var(--text-secondary)', margin: '0 0 24px' }}>
            Choose your preferred format to download real records from the server.
          </p>

          {error && (
            <div style={{ background: '#FEF2F2', border: '1px solid #FCA5A5', color: '#B91C1C', borderRadius: '8px', padding: '10px 14px', fontSize: '12.5px', marginBottom: '16px' }}>{error}</div>
          )}

          <div style={{ display: 'flex', flexDirection: 'column', gap: '14px' }}>
            {exportOptions.map((opt) => {
              const Icon = opt.icon;
              const isBusy = busy === opt.id;
              return (
                <button
                  key={opt.id}
                  onClick={() => handleExport(opt.id)}
                  disabled={Boolean(busy)}
                  style={{ display: 'flex', alignItems: 'center', gap: '16px', padding: '20px 24px', borderRadius: 'var(--radius-sm)', border: '1px solid var(--border)', background: '#fff', cursor: busy ? 'default' : 'pointer', fontFamily: 'inherit', textAlign: 'left', width: '100%', opacity: busy && !isBusy ? 0.6 : 1 }}
                >
                  <div style={{ width: '48px', height: '48px', borderRadius: '12px', background: opt.bg, display: 'flex', alignItems: 'center', justifyContent: 'center', flexShrink: 0 }}>
                    <Icon size={24} color={opt.color} />
                  </div>
                  <div style={{ flex: 1 }}>
                    <h4 style={{ fontSize: '15px', fontWeight: 700, margin: '0 0 4px', color: 'var(--text-primary)' }}>{opt.label}</h4>
                    <p style={{ fontSize: '13px', color: 'var(--text-secondary)', margin: 0 }}>{isBusy ? 'Preparing download...' : opt.desc}</p>
                  </div>
                  <Download size={20} color="var(--text-secondary)" />
                </button>
              );
            })}
          </div>
        </div>
      </main>
    </div>
  );
}
